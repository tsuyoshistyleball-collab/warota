// 長いパターンを先に並べた1本の正規表現にする。左から順に一番長い語を拾い、
// 「パプアニューギニア」の中の「ギニア」や「中南米」の中の「米」を二重に数えない
const ENTRIES = KEYWORDS.map(([source, region, weight]) => ({
  source,
  region,
  weight,
  // 先読み・後読みを除いた見かけの長さ。長い語を優先するための並び替えに使う
  len: source.replace(/\(\?<?[=!][^)]*\)/g, "").length,
})).sort((a, b) => b.len - a.len);
const MATCHER = new RegExp(ENTRIES.map((e, i) => `(?<k${i}>${e.source})`).join("|"), "gu");

// 文字列に出てくる地域ごとのスコア { region: {score, first} } を返す。
// 文頭に近い地名ほど主題である可能性が高いので重みを上げる
export function regionScores(text) {
  const scores = new Map();
  if (!text) return scores;
  const s = text.normalize("NFKC");
  for (const m of s.matchAll(MATCHER)) {
    const idx = Number(Object.keys(m.groups).find((k) => m.groups[k] !== undefined).slice(1));
    const { region, weight } = ENTRIES[idx];
    const pos = m.index < 6 ? 1.5 : m.index < 12 ? 1.2 : 1;
    for (const r of [region].flat()) {
      const cur = scores.get(r) ?? { score: 0, first: m.index };
      cur.score += weight * pos;
      cur.first = Math.min(cur.first, m.index);
      scores.set(r, cur);
    }
  }
  return scores;
}

// 記事 {title, description} を地域に振り分け、[{region, relevance}] を返す (主な地域が先頭)。
// kind: "japan" = 国内ニュースのフィード / "mixed" = 国内外が混在 / "world" = 海外ニュース中心
export function classify(item, kind) {
  if (kind === "japan") return [{ region: "japan", relevance: 1 }];

  const title = regionScores(item.title);
  const desc = regionScores((item.description ?? "").slice(0, 160));
  const total = new Map();
  for (const [region, { score }] of title) total.set(region, score);
  for (const [region, { score }] of desc) total.set(region, (total.get(region) ?? 0) + score * 0.4);

  // 日本は「外国の地名が出てこない記事」の受け皿にする
  const japanScore = total.get("japan") ?? 0;
  total.delete("japan");
  const ranked = [...total].filter(([region, score]) => title.has(region) || score >= 1).sort((a, b) => b[1] - a[1]);

  if (ranked.length === 0) {
    if (kind === "mixed" || japanScore > 0) return [{ region: "japan", relevance: 1 }];
    return [];
  }
  const [top, topScore] = ranked[0];
  const out = [{ region: top, relevance: 1 }];
  // 見出しに国名が出てくる2番目の地域も対象にする (例: 米中首脳会談 → 北米とアジア)
  const second = ranked[1];
  if (second && (title.get(second[0])?.score ?? 0) >= 0.9 && second[1] >= topScore * 0.5) {
    out.push({ region: second[0], relevance: 0.7 });
  }
  return out;
}
